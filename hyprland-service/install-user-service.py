#!/usr/bin/env python3
"""Install an isolated release and user unit; never copy credentials or captures."""
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile

MARKER = "# Generated by linux-computer-use-service installer"


def atomic_text(path, text, mode):
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=".linux-cua-", dir=path.parent)
    try:
        with os.fdopen(fd, "w") as stream:
            stream.write(text)
        os.chmod(temporary, mode)
        os.replace(temporary, path)
    finally:
        Path(temporary).unlink(missing_ok=True)


def install(source, destination, unit_path, client_path, reload=True):
    source, destination = Path(source).resolve(), Path(destination).absolute()
    unit_path, client_path = Path(unit_path), Path(client_path)
    driver = source / "bin/linux-cua-wtype"
    if not driver.is_file() or not os.access(driver, os.X_OK):
        raise RuntimeError("Build the private driver first: python3 build-driver.py")
    if client_path.exists() and MARKER not in client_path.read_text():
        raise RuntimeError(f"Refusing to replace unrelated executable: {client_path}")
    files = sorted((source / "linux_cua").glob("*.py")) + [driver]
    for relative in ("README.md", "LICENSE", "vendor/wtype/LICENSE", "vendor/wtype/PROVENANCE.md"):
        if (source / relative).is_file():
            files.append(source / relative)
    manifest = {str(p.relative_to(source)): hashlib.sha256(p.read_bytes()).hexdigest() for p in files}
    release_id = hashlib.sha256(json.dumps(manifest, sort_keys=True).encode()).hexdigest()[:20]
    releases = destination / "releases"
    releases.mkdir(parents=True, exist_ok=True, mode=0o700)
    release = releases / release_id
    if not release.exists():
        staging = Path(tempfile.mkdtemp(prefix=".staging-", dir=releases))
        try:
            for path in files:
                target = staging / path.relative_to(source)
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(path, target)
                target.chmod(0o755 if path == driver else 0o644)
            (staging / "installed-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
            os.replace(staging, release)
        finally:
            if staging.exists():
                shutil.rmtree(staging)
    else:
        for relative, expected in manifest.items():
            if hashlib.sha256((release / relative).read_bytes()).hexdigest() != expected:
                raise RuntimeError("Existing installed release changed; refusing to reuse it")
    current = destination / "current"
    if current.exists() and not current.is_symlink():
        raise RuntimeError("Install current path exists and is not a symlink")
    temporary_link = destination / (".current-" + release_id)
    temporary_link.unlink(missing_ok=True)
    temporary_link.symlink_to(Path("releases") / release_id)
    os.replace(temporary_link, current)
    # A unit path is not an ExecStart argument list; escape systemd whitespace.
    escaped = str(current).replace("\\", "\\\\").replace("%", "%%")
    escaped = escaped.replace(" ", "\\x20").replace("\t", "\\x09").replace("\n", "\\x0a")
    unit = (source / "systemd/linux-computer-use.service.in").read_text().replace("@SOURCE_DIR@", escaped)
    if unit_path.exists():
        atomic_text(unit_path.with_suffix(".service.previous"), unit_path.read_text(), 0o600)
    atomic_text(unit_path, unit, 0o600)
    wrapper = ("#!/usr/bin/python3\n" + MARKER + "\nimport sys\nsys.path.insert(0, "
               + repr(str(current)) + ")\nfrom linux_cua.__main__ import entry\nentry()\n")
    atomic_text(client_path, wrapper, 0o755)
    if reload:
        subprocess.run(["systemctl", "--user", "daemon-reload"], check=True)
    return {"release": str(release), "current": str(current), "unit": str(unit_path),
            "client": str(client_path), "files": len(files)}


if __name__ == "__main__":
    home = Path.home()
    print(json.dumps(install(Path(__file__).resolve().parent,
                             home / ".local/share/linux-computer-use-service",
                             home / ".config/systemd/user/linux-computer-use.service",
                             home / ".local/bin/linux-cua"), indent=2))
